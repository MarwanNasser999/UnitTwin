import fs from 'fs';
import path from 'path';

const texturesDir = path.join(process.cwd(), 'public', 'textures');
const outputPath = path.join(process.cwd(), 'src', 'texturesGenerated.js');

const folders = fs.readdirSync(texturesDir).filter((name) => {
  return fs.statSync(path.join(texturesDir, name)).isDirectory();
});

const entries = folders.map((folderName) => {
  // Turn "WoodFloor007_2K-JPG" into a readable label like "Wood Floor 007"
  const label = folderName
    .replace(/_2K-JPG$/i, '')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/([A-Za-z])(\d)/g, '$1 $2');

  const id = folderName.toLowerCase().replace(/[^a-z0-9]+/g, '_');

  return { id, label, textureFolder: folderName };
});

const fileContent = `// AUTO-GENERATED by generate-textures.js — do not edit by hand.
// Re-run "node generate-textures.js" after adding/removing texture folders.
export const generatedTextures = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(outputPath, fileContent);
console.log(`Generated ${entries.length} texture entries into texturesGenerated.js`);